'use strict';
const assert=require('node:assert/strict'),path=require('node:path'),fs=require('node:fs'),os=require('node:os');
const screenshots=process.env.REBORN_SCREENSHOTS||path.join(os.tmpdir(),'reborn-pass05-screenshots');fs.mkdirSync(screenshots,{recursive:true});
require('./garage-browser-check.cjs').withBrowser(async browser=>{
 const inspect=async code=>JSON.parse(await browser('eval',code));
 const waitFor=async(code,timeout=18000)=>JSON.parse(await browser('eval',`new Promise((resolve,reject)=>{const started=performance.now();const poll=()=>{let value=false;try{value=(${code});}catch(error){reject(error);return;}if(value){resolve(value);return;}if(performance.now()-started>${timeout}){resolve({timeout:true,town:window.REBORN?.snapshot()?.town?.minuteOfDay,passengers:window.REBORN?.snapshot()?.passengers,hidden:document.getElementById('passenger-choice')?.hidden});return;}setTimeout(poll,100);};poll();})`));
 await browser('set','viewport','1366','900');await browser('wait','1500');
 assert.equal(await inspect("document.getElementById('passenger-open')!==null"),true);
 assert.equal(await inspect("REBORN.snapshot().passengers.state.completed.length"),0);
 await browser('click','#passenger-open');
 assert.equal(await inspect("REBORN.snapshot().appState"),'journey');
 assert.equal(await inspect("document.getElementById('ux-panel-stories').hidden"),false);
 assert.equal(await inspect("document.querySelectorAll('[data-passenger-story]').length"),3);
 assert.equal(await inspect("document.querySelector('[data-passenger-story=\"last-part\"]').disabled"),true);
 await browser('screenshot',path.join(screenshots,'passenger-hub.png'));
 await browser('click','[data-passenger-story="long-way-home"]');await browser('wait','1200');
 assert.equal(await inspect("REBORN.snapshot().appState"),'play');
 assert.equal(await inspect("REBORN.snapshot().passengers.active.id"),'long-way-home');
 assert.equal(await inspect("REBORN.snapshot().passengers.active.phase"),'ride');
 assert.ok((await inspect("document.querySelector('.mission').textContent")).toUpperCase().includes('MARA'));
 const promptWait=await waitFor("!document.getElementById('passenger-choice').hidden",18000);
 assert.equal(promptWait,true,`Passenger prompt did not open after boarding: ${JSON.stringify(promptWait)}`);
 assert.equal(await inspect("document.querySelectorAll('[data-passenger-choice]').length"),3);
 await browser('screenshot',path.join(screenshots,'passenger-choice.png'));
 await browser('click','[data-passenger-choice="silence"]');await browser('wait','300');
 assert.equal(await inspect("document.getElementById('passenger-choice').hidden"),true);
 assert.equal(await inspect("REBORN.snapshot().passengers.active.commitment"),'avoid-mill');
 assert.equal(await inspect("REBORN.snapshot().passengers.state.stats.silences"),1);
 assert.equal(await inspect("document.getElementById('passenger-dialogue').hidden"),false);
 await browser('press','j');await browser('click','#ux-tab-stories');
 assert.equal(await inspect("document.querySelector('.passenger-story-card.active')!==null"),true);
 await browser('press','Escape');assert.equal(await inspect("REBORN.snapshot().appState"),'play');
 await browser('reload');await browser('wait','1200');
 assert.equal(await inspect("REBORN.snapshot().passengers.active.id"),'long-way-home');
 assert.equal(await inspect("REBORN.snapshot().passengers.active.commitment"),'avoid-mill');
 await browser('click','#passenger-open');
 assert.equal(await inspect("document.querySelector('[data-passenger-story=\"long-way-home\"]').textContent.includes('RESUME')"),true);
 await browser('click','[data-passenger-story="long-way-home"]');await browser('wait','800');
 assert.equal(await inspect("REBORN.snapshot().appState"),'play');
 assert.equal(await inspect("REBORN.snapshot().passengers.active.id"),'long-way-home');
 assert.deepEqual(await inspect('REBORN.snapshot().errors'),[]);
 console.log('Passenger-drive browser acceptance: hub, sequential locking, pickup, in-drive dialogue choice, explicit silence, Jetta tab, persistence and resume passed.');
},{viewport:[1366,900]});
